// Helper function to filter groups
export const filterGroups = (groups, filters) => {
  return groups.filter((group) => {
    const matchesSearch =
      !filters.search ||
      group.moduleName.toLowerCase().includes(filters.search.toLowerCase()) ||
      group.groupName.toLowerCase().includes(filters.search.toLowerCase());

    const matchesModule =
      filters.module === "All Modules" || group.moduleName === filters.module;

    const matchesStatus =
      filters.status === "All" || group.status === filters.status;

    return matchesSearch && matchesModule && matchesStatus;
  });
};

// Helper function to get stats
export const getGroupStats = (groups, currentUserItNumber) => {
  return {
    totalGroups: groups.length,
    openGroups: groups.filter((g) => g.status === "Open").length,
    fullGroups: groups.filter((g) => g.status === "Full").length,
    myGroups: groups.filter((g) =>
      g.members.some((m) => m.itNumber === currentUserItNumber)
    ).length,
  };
};

